/**
 * Russian localization for the Telegram console.
 *
 * Upstream ships Simplified-Chinese literals with no i18n layer, so this fork
 * keeps the logic untouched and translates at the edges: every outgoing text
 * (and keyboard label) passes through {@link localize} before it reaches
 * Telegram. `callback_data` is never translated, and reply-keyboard labels are
 * ASCII commands, so command routing keeps working.
 *
 * Number-bearing strings are handled by {@link RUSSIAN_PATTERNS} (with proper
 * Russian plurals through {@link plural}); everything else is a plain
 * phrase table, applied longest-first so longer sentences win over fragments.
 *
 * @module @maotsk/dsh-host-telegram/locale-ru
 */

/** Locale of the chat surface. */
export type BotLocale = 'ru' | 'zh'

/**
 * Pick one of three Russian plural forms for a count.
 * @param count - the number the noun agrees with.
 * @param forms - `[one, few, many]`, e.g. `['сессия', 'сессии', 'сессий']`.
 * @returns the matching form.
 */
export function plural(count: number, forms: readonly [string, string, string]): string {
  const abs = Math.abs(count) % 100
  const tail = abs % 10
  if (abs > 10 && abs < 20) return forms[2]
  if (tail > 1 && tail < 5) return forms[1]
  if (tail === 1) return forms[0]
  return forms[2]
}

/**
 * Number-aware rewrites, applied before the phrase table. A replacement may be
 * a function so the number can drive Russian agreement.
 */
export const RUSSIAN_PATTERNS: ReadonlyArray<readonly [RegExp, string | ((...args: string[]) => string)]> = [
  // Relative age labels: the count drives Russian agreement through `plural`,
  // so "5 分钟前" becomes "5 минут назад", not a calqued fragment.
  [/^刚刚$/, 'только что'],
  [/(\d+)\s*分钟前/, (...args) => `${args[1]} ${plural(Number(args[1]), ['минуту', 'минуты', 'минут'])} назад`],
  [/(\d+)\s*小时前/, (...args) => `${args[1]} ${plural(Number(args[1]), ['час', 'часа', 'часов'])} назад`],
  [/(\d+)\s*天前/, (...args) => `${args[1]} ${plural(Number(args[1]), ['день', 'дня', 'дней'])} назад`],
  // Counted nouns: sessions, dialogue rounds, messages, models, characters.
  [/(\d+)\s*个会话/, (...args) => `${args[1]} ${plural(Number(args[1]), ['сессия', 'сессии', 'сессий'])}`],
  [/(\d+)\s*轮对话/, (...args) => `${args[1]} ${plural(Number(args[1]), ['раунд', 'раунда', 'раундов'])} диалога`],
  [/(\d+)\s*条消息/, (...args) => `${args[1]} ${plural(Number(args[1]), ['сообщение', 'сообщения', 'сообщений'])}`],
  [/(\d+)\s*个模型/, (...args) => `${args[1]} ${plural(Number(args[1]), ['модель', 'модели', 'моделей'])}`],
  [/(\d+)\s*个?字符/, (...args) => `${args[1]} ${plural(Number(args[1]), ['символ', 'символа', 'символов'])}`],
]

