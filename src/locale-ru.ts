/** Phrases sorted longest-first so a full sentence beats its fragments. */
const orderedPhrases: ReadonlyArray<readonly [string, string]> = [...RUSSIAN_PHRASES]
  .sort((left, right) => right[0].length - left[0].length)

/**
 * Translate one outgoing string.
 * @param text - the text as the console produced it.
 * @param locale - the configured chat locale.
 * @returns Russian text for `ru`, the input untouched otherwise.
 */
export function localize(text: string, locale: BotLocale): string {
  if (locale !== 'ru' || text === '') return text
  let result = text
  for (const [pattern, replacement] of RUSSIAN_PATTERNS) {
    result = typeof replacement === 'string'
      ? result.replace(pattern, replacement)
      : result.replace(pattern, (...args: string[]) => replacement(...args))
  }
  for (const [from, to] of orderedPhrases) {
    if (from !== '' && result.includes(from)) result = result.split(from).join(to)
  }
  return result
}

/**
 * Translate a keyboard's labels in place-preserving fashion.
 * @param rows - rows of buttons carrying a `text` label.
 * @param locale - the configured chat locale.
 * @returns new rows with translated labels; `callback_data` is left alone.
 */
export function localizeRows<T extends { text: string }>(rows: readonly (readonly T[])[], locale: BotLocale): T[][] {
  return rows.map(row => row.map(button => ({ ...button, text: localize(button.text, locale) })))
}
